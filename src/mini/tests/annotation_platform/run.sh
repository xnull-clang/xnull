#!/bin/sh
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(git -C "$HERE" rev-parse --show-toplevel)
PLATFORM="$ROOT/src/toolchain/annotation_platform.py"
MINI="$ROOT/src/mini/bin/mini"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --out "$TMP/out1"
grep -q 'generated by toy_processor' "$TMP/out1/toy_generated.x"
python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --out "$TMP/out2"
cmp "$TMP/out1/toy_generated.x" "$TMP/out2/toy_generated.x"

cat > "$TMP/fail_source.x" <<'X'
package app
@annotation Toy { final Bool fail = false }
@Toy(true)
class Device { }
static Int main() { return 0 }
X
if python3 "$PLATFORM" generate --entry "$TMP/fail_source.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --out "$TMP/failout" >"$TMP/fail.stdout" 2>"$TMP/fail.stderr"; then
    echo "annotation_platform: @Toy(true) accepted" >&2
    exit 1
fi
grep -q 'AN1001' "$TMP/failout/diagnostics.json"

python3 - "$TMP" <<'PY'
import json
import sys
from pathlib import Path
base = Path(sys.argv[1])
base_manifest = json.loads(Path('src/mini/tests/annotation_platform/manifest.json').read_text())
def write(name, proc):
    data = {"manifestVersion": 1, "processors": [proc]}
    (base/name).write_text(json.dumps(data), encoding='utf-8')
proc = base_manifest['processors'][0]
for name, mutate in [
    ('bad_phase.json', lambda p: p.update(phases=['Bad'])),
    ('bad_output.json', lambda p: p.update(outputs=['../x'])),
    ('bad_timeout.json', lambda p: p.update(timeoutSeconds=0)),
]:
    p = dict(proc); mutate(p); write(name, p)
p1 = dict(proc); p1['name'] = 'dup'; write('dup.json', p1)
data = json.loads((base/'dup.json').read_text()); data['processors'].append(dict(p1)); (base/'dup.json').write_text(json.dumps(data))
PY
for bad in bad_phase.json bad_output.json bad_timeout.json dup.json; do
    if python3 "$PLATFORM" check-manifest --manifest "$TMP/$bad" >"$TMP/$bad.out" 2>&1; then
        echo "annotation_platform: invalid manifest accepted: $bad" >&2
        exit 1
    fi
done

cat > "$TMP/slow.py" <<'PY'
import argparse, time
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
time.sleep(2)
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"slow","phases":["Generate"],"command":["python3",str(base/"slow.py")],"outputs":[],"timeoutSeconds":1,"priority":0}]}
(base/"slow.json").write_text(json.dumps(m))
PY
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/slow.json" --out "$TMP/slowout" >"$TMP/slow.stdout" 2>"$TMP/slow.stderr"; then
    echo "annotation_platform: timeout accepted" >&2
    exit 1
fi
grep -q 'timeout' "$TMP/slow.stderr"

cat > "$TMP/nonzero.py" <<'PY'
import sys
sys.exit(3)
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"nonzero","phases":["Generate"],"command":["python3",str(base/"nonzero.py")],"outputs":[],"timeoutSeconds":5,"priority":0}]}
(base/"nonzero.json").write_text(json.dumps(m))
PY
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/nonzero.json" --out "$TMP/nonzeroout" >"$TMP/nonzero.stdout" 2>"$TMP/nonzero.stderr"; then
    echo "annotation_platform: nonzero processor accepted" >&2
    exit 1
fi
grep -q 'exit 3' "$TMP/nonzero.stderr"

cat > "$TMP/diag.py" <<'PY'
import argparse, json
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
if a.phase != 'Generate':
    raise SystemExit(0)
out=Path(a.out); out.mkdir(parents=True, exist_ok=True)
diags=[
 {"code":"AN1002","severity":"Warning","message":"w","line":2,"col":1,"target":"app.X"},
 {"code":"AN1001","severity":"Error","message":"e","line":2,"col":1,"target":"app.X"},
 {"code":"AN1001","severity":"Error","message":"e","line":2,"col":1,"target":"app.X"},
]
(out/'diagnostics.json').write_text(json.dumps(diags))
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"diag","phases":["Generate"],"command":["python3",str(base/"diag.py")],"outputs":[],"timeoutSeconds":5,"priority":0}]}
(base/"diag.json").write_text(json.dumps(m))
PY
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/diag.json" --out "$TMP/diagout" >"$TMP/diag.stdout" 2>"$TMP/diag.stderr"; then
    echo "annotation_platform: Error diagnostics accepted" >&2
    exit 1
fi
python3 - "$TMP/diagout/diagnostics.json" <<'PY'
import json, sys
items=json.load(open(sys.argv[1]))
assert [i['severity'] for i in items] == ['Error','Warning'], items
assert len(items) == 2, items
PY

cat > "$TMP/phases.py" <<'PY'
import argparse, sys
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
print('PHASE=' + a.phase, file=sys.stderr)
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"phases","phases":["Finalize","Generate","Validate","Resolve"],"command":["python3",str(base/"phases.py")],"outputs":[],"timeoutSeconds":5,"priority":0}]}
(base/"phases.json").write_text(json.dumps(m))
PY
python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/phases.json" --out "$TMP/phasesout" >"$TMP/phases.stdout" 2>"$TMP/phases.stderr"
python3 - "$TMP/phasesout/report.json" <<'PY'
import json, sys
reports=json.load(open(sys.argv[1]))['processors']
seen=[]
for r in reports:
    for line in r.get('stderr','').splitlines():
        if line.startswith('PHASE='):
            seen.append(line.split('=',1)[1])
assert seen == ['Resolve','Validate','Generate','Finalize'], seen
PY

echo "annotation_platform: PASS"

# M0.3 generated-dir / fixed point / check / atomic
mkdir -p "$TMP/project"
cp "$HERE/source.x" "$TMP/project/source.x"
cat > "$TMP/project/fixed.x" <<'X'
package app
import generated.toy_generated
@annotation Toy { final Bool fail = false }
@Toy
class Device { }
static Int main() { return 0 }
X
python3 "$PLATFORM" generate --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated"
test -f "$TMP/project/generated/toy_generated.x"
grep -q 'generated by toy_processor' "$TMP/project/generated/toy_generated.x"
python3 "$PLATFORM" generate --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated"
python3 "$PLATFORM" check --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated" >/dev/null

cp "$TMP/project/generated/toy_generated.x" "$TMP/toy.orig"
printf '\n// drift\n' >> "$TMP/project/generated/toy_generated.x"
if python3 "$PLATFORM" check --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated" >/dev/null 2>&1; then
    echo "annotation_platform: drift accepted" >&2; exit 1
fi
cp "$TMP/toy.orig" "$TMP/project/generated/toy_generated.x"
rm "$TMP/project/generated/toy_generated.x"
if python3 "$PLATFORM" check --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated" >/dev/null 2>&1; then
    echo "annotation_platform: missing accepted" >&2; exit 1
fi
python3 "$PLATFORM" generate --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated" >/dev/null
printf 'extra\n' > "$TMP/project/generated/extra.x"
if python3 "$PLATFORM" check --entry "$TMP/project/fixed.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$HERE/manifest.json" --generated-dir "$TMP/project/generated" >/dev/null 2>&1; then
    echo "annotation_platform: extra accepted" >&2; exit 1
fi
rm "$TMP/project/generated/extra.x"

cat > "$TMP/badmarker.py" <<'PY'
import argparse
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
if a.phase == 'Generate':
    (Path(a.out)/'bad.x').write_text('package app\n')
PY
python3 - "$TMP" "$ROOT" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"badmarker","phases":["Generate"],"command":["python3",str(base/"badmarker.py")],"outputs":["bad.x"],"timeoutSeconds":5,"priority":0}]}
(base/"badmarker.json").write_text(json.dumps(m))
PY
mkdir -p "$TMP/atomic"
printf 'old\n' > "$TMP/atomic/toy_generated.x"
if python3 "$PLATFORM" generate --entry "$TMP/project/source.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$TMP/badmarker.json" --generated-dir "$TMP/atomic" >/dev/null 2>&1; then
    echo "annotation_platform: unmarked accepted" >&2; exit 1
fi
grep -q '^old$' "$TMP/atomic/toy_generated.x"

cat > "$TMP/nonconv.py" <<'PY'
import argparse, time
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
if a.phase == 'Generate':
    (Path(a.out)/'grow.x').write_text('// generated by nonconv; DO NOT EDIT\npackage app\n// ' + str(time.time()))
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
m={"manifestVersion":1,"processors":[{"name":"nonconv","phases":["Generate"],"command":["python3",str(base/"nonconv.py")],"outputs":["grow.x"],"timeoutSeconds":5,"priority":0}]}
(base/"nonconv.json").write_text(json.dumps(m))
PY
if python3 "$PLATFORM" generate --entry "$TMP/project/source.x" --xdk-root "$ROOT/src/xdk" \
    --manifest "$TMP/nonconv.json" --generated-dir "$TMP/nonconv" --max-rounds 2 >/dev/null 2>&1; then
    echo "annotation_platform: non-convergence accepted" >&2; exit 1
fi

# M0.4 sandbox / limits
BACKEND=$(python3 -c "import json,sys; print(json.load(open(sys.argv[1]))['sandboxBackend'])" "$TMP/out1/report.json")
echo "annotation_platform: sandboxBackend=$BACKEND"
if [ "$BACKEND" = "darwin-sandbox-exec" ]; then
    test "$(uname -s)" = "Darwin"
fi

cat > "$TMP/escape.py" <<'PY'
import argparse
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
Path(a.out).mkdir(parents=True, exist_ok=True)
Path(a.out, '..', 'escape.x').write_text('x')
Path('/tmp/xnull_sandbox_escape').write_text('x')
PY
cat > "$TMP/net.py" <<'PY'
import argparse, socket
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
s=socket.socket(); s.settimeout(1); s.connect(('127.0.0.1', 9))
PY
cat > "$TMP/mem.py" <<'PY'
import argparse
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
x = bytearray(200 * 1024 * 1024)
PY
cat > "$TMP/cpu.py" <<'PY'
import argparse
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
while True:
    pass
PY
cat > "$TMP/sym.py" <<'PY'
import argparse, os
from pathlib import Path
p=argparse.ArgumentParser(); p.add_argument('--phase'); p.add_argument('--ir'); p.add_argument('--out'); a=p.parse_args()
os.symlink('/tmp', Path(a.out) / 'link')
PY
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
def write(name, sandbox, timeout=2):
    proc={'name':name,'phases':['Generate'],'command':['python3',str(base/(name+'.py'))],'outputs':[],'timeoutSeconds':timeout,'priority':0,'sandbox':sandbox}
    (base/(name+'.json')).write_text(json.dumps({'manifestVersion':1,'processors':[proc]}))
write('escape', {})
write('net', {})
write('mem', {'maxMemoryMB':64})
write('cpu', {'maxCpuSeconds':1}, 2)
write('sym', {})
PY
rm -f /tmp/xnull_sandbox_escape
if [ "$BACKEND" = "darwin-sandbox-exec" ]; then
    if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/escape.json" --generated-dir "$TMP/sandbox_escape" >/dev/null 2>&1; then
        echo "annotation_platform: sandbox escape accepted" >&2; exit 1
    fi
    test ! -e /tmp/xnull_sandbox_escape
    if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/net.json" --generated-dir "$TMP/sandbox_net" >/dev/null 2>&1; then
        echo "annotation_platform: sandbox network accepted" >&2; exit 1
    fi
else
    echo "annotation_platform: escape/network sandbox checks SKIP (backend limits-only)"
fi
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/mem.json" --generated-dir "$TMP/sandbox_mem" >/dev/null 2>&1; then
    echo "annotation_platform: memory limit accepted" >&2; exit 1
fi
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/cpu.json" --generated-dir "$TMP/sandbox_cpu" >/dev/null 2>&1; then
    echo "annotation_platform: cpu limit accepted" >&2; exit 1
fi
if python3 "$PLATFORM" generate --entry "$HERE/source.x" --xdk-root "$ROOT/src/xdk" --manifest "$TMP/sym.json" --generated-dir "$TMP/sandbox_sym" >/dev/null 2>&1; then
    echo "annotation_platform: symlink accepted" >&2; exit 1
fi

# invalid sandbox manifests
python3 - "$TMP" <<'PY'
import json, sys
from pathlib import Path
base=Path(sys.argv[1])
proc={'name':'p','phases':['Generate'],'command':['python3','x.py'],'outputs':[],'timeoutSeconds':5,'priority':0}
for name, sandbox in [
    ('allow_net', {'allowNetwork':True}),
    ('extra', {'bogus':1}),
    ('mem_low', {'maxMemoryMB':8}),
    ('cpu_high', {'maxCpuSeconds':121}),
]:
    p=dict(proc); p['sandbox']=sandbox
    (base/(name+'.json')).write_text(json.dumps({'manifestVersion':1,'processors':[p]}))
PY
for bad in allow_net.json extra.json mem_low.json cpu_high.json; do
    if python3 "$PLATFORM" check-manifest --manifest "$TMP/$bad" >"$TMP/$bad.out" 2>&1; then
        echo "annotation_platform: invalid sandbox manifest accepted: $bad" >&2; exit 1
    fi
done
