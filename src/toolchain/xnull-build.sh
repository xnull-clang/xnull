#!/usr/bin/env bash
# XNull build/run/check — mini only.
#
# mini is the canonical compiler. There is no hidden second code generator.
# Project/package commands are
# intentionally absent until mini owns them; single-file XNull is the current
# product surface.
set -uo pipefail
trap 'exit 130' INT

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=${XNULL_ROOT:-$(cd "$HERE/../.." && pwd)}
RUNTIME="$ROOT/src/runtime"
MINI="$ROOT/src/mini/bin/mini"
CACHE_DIR=${XNULL_CACHE_DIR:-$ROOT/.cache/xnull}
mkdir -p "$CACHE_DIR" 2>/dev/null || true

RUNTIME_SRCS=(
  rt.c rt_gc.c rt_policy.c rt_weak.c xrt_abi.c
  rt_std_runtime.c rt_std_text.c rt_std_sys.c rt_std_bytes.c rt_std_net.c
  rt_task.c rt_sync.c rt_std_res.c rt_std_res_empty.c rt_std_ext.c
)

die() { echo "xnull-build: $*" >&2; exit 2; }
fail() { echo "xnull-build: $*" >&2; exit 1; }
usage() {
  cat >&2 <<'EOF'
xnull-build: mini-only commands
  build <entry.x> [-o out] [--emit-c-only] [--resources dir] [--json]
  run   <entry.x> [-- args] [--json]
  check <entry.x> [--json]
  version
  clean [--all]
  doctor
EOF
  exit 2
}

require_mini() {
  [ -x "$MINI" ] || fail "mini compiler missing: run src/mini/build.sh"
}

resolve_entry() {
  local entry=$1
  if [ -f "$entry" ]; then
    printf '%s\n' "$entry"
    return 0
  fi
  if [ -f "$ROOT/$entry" ]; then
    printf '%s\n' "$ROOT/$entry"
    return 0
  fi
  die "entry not found: $entry"
}

workdir() {
  mktemp -d "${TMPDIR:-/tmp}/xnull-build.XXXXXX"
}

emit_c() {
  local entry=$1 outdir=$2 out=$3
  require_mini
  mkdir -p "$outdir"
  local entry_abs; entry_abs=$(resolve_entry "$entry")
  local entry_dir; entry_dir=$(dirname "$entry_abs")
  : > "$outdir/project.txt"
  if [ -d "$entry_dir" ]; then
    python3 "$ROOT/src/toolchain/xfb-projection.py" "$entry_dir" >> "$outdir/project.txt" 2>/dev/null || true
  fi
  python3 "$ROOT/src/toolchain/xfb-projection.py" "$ROOT/src/ffi" >> "$outdir/project.txt" 2>/dev/null || true
  local extra=()
  if [ "${XNULL_MINI_XDK_FULL:-0}" = "1" ]; then
    extra+=(--xdk-full)
  fi
  ( cd "$ROOT" && "$MINI" --emit-c "$entry_abs" \
      --xdk-root "$ROOT/src/xdk" \
      --project-file "$outdir/project.txt" \
      ${extra[@]+"${extra[@]}"} ) > "$out" 2> "$outdir/mini.err"
  local rc=$?
  if [ $rc -ne 0 ]; then
    sed -n 1,12p "$outdir/mini.err" >&2
    sed -n 1,12p "$out" >&2
    return 1
  fi
}

write_empty_res() {
  cat > "$1" <<'EOF'
/* generated by xnull build: empty resource table */
#include <stddef.h>
#include <string.h>

size_t xrt_resource_count(void) { return 0; }

int xrt_resource_get(const char *name, size_t nlen,
                     const unsigned char **out, size_t *out_len) {
    (void)name; (void)nlen;
    *out = 0; *out_len = 0;
    return 1;
}

int xrt_resource_at(size_t i, const char **name, size_t *nlen,
                    const unsigned char **out, size_t *out_len) {
    (void)i;
    *name = 0; *nlen = 0; *out = 0; *out_len = 0;
    return 1;
}
EOF
}

cc_link() {
  local cfile=$1 out=$2 res=$3
  local srcs=()
  local s
  for s in "${RUNTIME_SRCS[@]}"; do srcs+=("$RUNTIME/$s"); done
  if ! cc -std=c11 -O2 -pthread -I "$RUNTIME" -o "$out" "$cfile" "${srcs[@]}" "$res" -lz 2> "${out}.cc.log"; then
    sed -n 1,12p "${out}.cc.log" >&2
    fail "cc link failed: $cfile"
  fi
}

json_build() {
  local ok=$1 target=$2 output=$3 code=$4 diag=$5 log=$6
  python3 "$ROOT/src/toolchain/json_result.py" "$ok" "$target" "$output" "$code" "$diag" "$log"
}

cmd_build() {
  local entry="" out="" emit_only=0 json=0 resources=${XNULL_RESOURCES:-}
  while [ $# -gt 0 ]; do
    case "$1" in
      -o|--output) out=${2:-}; shift 2 ;;
      --resources) resources=${2:-}; shift 2 ;;
      --emit-c-only) emit_only=1; shift ;;
      --json) json=1; shift ;;
      -*) die "unknown argument: $1" ;;
      *) entry=$1; shift ;;
    esac
  done
  [ -n "$entry" ] || usage
  local w; w=$(workdir) || exit 1
  local base
  if [ -n "$out" ]; then
    base=${out%.c}; base=${base%.exe}
  else
    base="$w/a.out"
  fi
  mkdir -p "$(dirname "$base")"
  local so="$w/build.out" se="$w/build.err"
  if ! emit_c "$entry" "$w" "$base.c" > "$so" 2> "$se"; then
    [ "$json" = 1 ] && json_build 1 "$entry" "" 1 "$se" "$se"
    cat "$se" >&2
    return 1
  fi
  if [ "$emit_only" = 1 ]; then
    echo "$base.c"
    return 0
  fi
  if [ -n "$resources" ] && [ -d "$resources" ]; then
    python3 "$ROOT/src/toolchain/gen_res_table.py" "$resources" "$base.res.c" \
      || fail "resource table failed: $resources"
  else
    write_empty_res "$base.res.c"
  fi
  if ! cc_link "$base.c" "$base" "$base.res.c"; then
    [ "$json" = 1 ] && json_build 1 "$entry" "" 1 "$base.cc.log" "$base.cc.log"
    return 1
  fi
  if [ "$json" = 1 ]; then
    json_build 0 "$entry" "$base" 0 "$se" "$se"
  else
    echo "$base"
  fi
}

cmd_run() {
  local entry="" json=0
  local extra=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --json) json=1; shift ;;
      --) shift; extra=("$@"); break ;;
      -*) die "unknown argument: $1" ;;
      *) entry=$1; shift ;;
    esac
  done
  [ -n "$entry" ] || usage
  local w; w=$(workdir) || exit 1
  local base="$w/a.out"
  local so="$w/run.out" se="$w/run.err"
  if ! emit_c "$entry" "$w" "$base.c" > "$so" 2> "$se"; then
    [ "$json" = 1 ] && json_build 1 "$entry" "" 1 "$se" "$se"
    cat "$se" >&2
    return 1
  fi
  write_empty_res "$base.res.c"
  if ! cc_link "$base.c" "$base" "$base.res.c" > "$so" 2> "$se"; then
    [ "$json" = 1 ] && json_build 1 "$entry" "" 1 "$se" "$se"
    return 1
  fi
  "$base" ${extra[@]+"${extra[@]}"} > "$so" 2> "$se"
  local rc=$?
  if [ "$json" = 1 ]; then
    json_build "$rc" "$entry" "$(cat "$so")" "$rc" "$se" "$se"
  else
    cat "$so"
    cat "$se" >&2
  fi
  return "$rc"
}

cmd_check() {
  local entry="" json=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --json) json=1; shift ;;
      -*) die "unknown argument: $1" ;;
      *) entry=$1; shift ;;
    esac
  done
  [ -n "$entry" ] || usage
  require_mini
  local entry_abs; entry_abs=$(resolve_entry "$entry")
  local out rc
  out=$( ( cd "$ROOT" && "$MINI" --sema "$entry_abs" --xdk-root "$ROOT/src/xdk" ) 2>&1 )
  rc=$?
  if [ "$json" = 1 ]; then
    if [ $rc -eq 0 ]; then
      printf '{"ok":true}\n'
    else
      local diag; diag=$(mktemp)
      printf '%s\n' "$out" > "$diag"
      json_build 1 "$entry_abs" "" "$rc" "$diag" "$diag"
      rm -f "$diag"
    fi
  else
    printf '%s\n' "$out"
  fi
  return "$rc"
}

cmd_version() {
  require_mini
  echo "xnull mini"
  echo "engine: mini"
  echo "compiler: $("$MINI" --version 2>/dev/null | head -1)"
}

cmd_clean() {
  local all=0
  [ "${1:-}" = "--all" ] && all=1
  rm -rf "$CACHE_DIR"
  if [ "$all" = 1 ]; then
    find "$ROOT" -type d -name target -prune -exec rm -rf {} + 2>/dev/null || true
  fi
  echo "clean: ok"
}

cmd_doctor() {
  local ok=0
  [ -x "$MINI" ] && echo "mini: $MINI" || { echo "mini: missing" >&2; ok=1; }
  [ -d "$RUNTIME" ] && echo "runtime: $RUNTIME" || { echo "runtime: missing" >&2; ok=1; }
  command -v cc >/dev/null 2>&1 && echo "cc: $(command -v cc)" || { echo "cc: missing" >&2; ok=1; }
  command -v python3 >/dev/null 2>&1 && echo "python3: $(command -v python3)" || { echo "python3: missing" >&2; ok=1; }
  [ -f "$ROOT/src/toolchain/xfb-projection.py" ] && echo "ffi projection: ok" || { echo "ffi projection: missing" >&2; ok=1; }
  echo "engine: mini"
  return "$ok"
}

cmd=${1:-}; shift || true
case "$cmd" in
  build) cmd_build "$@" ;;
  run) cmd_run "$@" ;;
  check) cmd_check "$@" ;;
  version) cmd_version "$@" ;;
  clean) cmd_clean "$@" ;;
  doctor) cmd_doctor "$@" ;;
  "") usage ;;
  *) die "unknown command: $cmd" ;;
esac
