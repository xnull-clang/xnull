#!/usr/bin/env python3
"""Toy external annotation processor for M0.2 protocol tests."""
import argparse
import json
import sys
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", required=True)
    parser.add_argument("--ir", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    ir = json.loads(Path(args.ir).read_text(encoding="utf-8"))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    uses = []
    for use in ir.get("uses", []):
        name = use.get("resolvedName") or use.get("name")
        if name == "app.Toy" or name == "Toy":
            uses.append(use)

    fail = False
    fail_line = 1
    fail_col = 1
    for use in uses:
        fail_line = use.get("line", 1)
        fail_col = use.get("col", 1)
        for arg in use.get("arguments", []):
            if arg.get("kind") == "bool" and arg.get("text") == "true":
                fail = True

    if fail:
        diags = [{
            "code": "AN1001",
            "severity": "Error",
            "message": "toy processor rejected @Toy(true)",
            "line": fail_line,
            "col": fail_col,
            "target": "app.Device",
        }]
        (out / "diagnostics.json").write_text(json.dumps(diags, ensure_ascii=False), encoding="utf-8")
        return 0

    if args.phase == "Generate" and uses:
        (out / "toy_generated.x").write_text(
            "// generated by toy_processor; DO NOT EDIT\n"
            "package app\n"
            "String toyValue() { return \"toy\"; }\n",
            encoding="utf-8",
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
