#!/usr/bin/env python3
"""P7-02: consume Constructor targets plus double/array annotation values."""
import argparse
import json
import sys
from pathlib import Path

WIDEN = "Widen"


def diag(code, message, target=""):
    return {"code": code, "severity": "Error", "message": message,
            "line": 1, "col": 1, "target": target}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--phase", required=True)
    parser.add_argument("--ir", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    if args.phase != "Generate":
        return 0
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    ir = json.loads(Path(args.ir).read_text(encoding="utf-8"))
    symbols = ir.get("symbols", {}).get("types", [])
    by_full = {t.get("fullName"): t for t in symbols}
    entries = []
    errors = []
    for use in ir.get("uses", []):
        name = (use.get("resolvedName") or use.get("name") or "").split(".")[-1]
        if name != WIDEN:
            continue
        target = use.get("target")
        target_name = use.get("targetName", "")
        if target != "Constructor":
            errors.append(diag("AN1501", "@Widen must target a constructor: " + target_name, target_name))
            continue
        arguments = use.get("arguments", [])
        if len(arguments) < 2 or arguments[0].get("kind") != "double" or arguments[1].get("kind") != "array":
            errors.append(diag("AN1501", "@Widen expects double + array values: " + target_name, target_name))
            continue
        tags = []
        for child in arguments[1].get("children", []):
            tags.append(child.get("text", ""))
        entries.append({"target": target_name, "factor": arguments[0].get("text", "0.0"),
                        "tags": tags, "line": use.get("line", 1)})

    if errors:
        out.joinpath("diagnostics.json").write_text(json.dumps(errors, ensure_ascii=False), encoding="utf-8")
        return 0

    package = "app.ext"
    if entries:
        owner = entries[0]["target"].split("#")[0]
        if owner in by_full:
            package = by_full[owner].get("package", package)

    lines = ["// generated by extension_processor; DO NOT EDIT", "package " + package, ""]
    entries.sort(key=lambda item: item["line"])
    index = 0
    for entry in entries:
        tags = ",".join(entry["tags"])
        suffix = str(index)
        lines.append("String extensionFactor" + suffix + "() { return " + json.dumps(entry["factor"]) + " }")
        lines.append("String extensionTags" + suffix + "() { return " + json.dumps(tags) + " }")
        lines.append("String extensionTarget" + suffix + "() { return " + json.dumps(entry["target"]) + " }")
        lines.append("")
        index += 1
    (out / "ExtensionGenerated.x").write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
